"""
Единая нормализация телефонных номеров (ТЗ п. 4.1, п. 1.2.1). Телефон —
фактический идентификатор клиента: по нему ищут, по нему ловят дубли при
импорте и при конвертации заявки. Если хранить как введено, три разных
написания одного номера будут тремя разными людьми — поэтому нормализация
должна быть одной функцией на всю систему, а не переизобретаться в каждом
домене (импорт, поиск дублей, приём заявок с сайта — TRU-3.1/4.1).

Формат хранения — E.164 (+7XXXXXXXXXX); формат отображения — задача
фронтенда, не этой функции.
"""

import re


class InvalidPhoneNumberError(ValueError):
    pass


def normalize_phone_number(raw: str) -> str:
    """
    Казахстанские (и российские — тот же код страны) номера: 11 цифр с
    ведущей "7" или "8" (8 — региональный трактовый префикс, эквивалентен
    международной "7"), либо 10 цифр без кода страны/трактового префикса.
    Всё, что не цифра (пробелы, скобки, дефисы, "+") — игнорируется.
    """
    digits = re.sub(r"\D", "", raw or "")

    if len(digits) == 10:
        digits = "7" + digits
    elif len(digits) == 11 and digits[0] == "8":
        digits = "7" + digits[1:]

    if len(digits) != 11 or digits[0] != "7":
        raise InvalidPhoneNumberError(f"Не похоже на телефон: {raw!r}")

    return f"+{digits}"
